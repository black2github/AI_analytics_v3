# tests/test_source_role_literals_obligation.py
"""Пакет П3 ОНБ-В, срез 5а (2026-11-09): литералы источника по роли «обязательность»
(`source_role_literals`, помилование дословного значения колонки обязательности карточки) —
по тому же перечню заголовков, что роль в `validate_columns` (`obligation_title`), а не по
подстроке «обяз»."""
from app.scripts.CI.kitcheck.checks.card_source import source_role_literals

ONBV_ERROR_HEAD = ("Сообщение об ошибке<br>На ЭФ сообщения об ошибке выводятся на конкретном поле, "
                   "поэтому &lt;название реквизита&gt; не указывается в тексте. Например, "
                   "\"Обязательное поле\".")


def _md(head, rows):
    out = "| " + " | ".join(head) + " |\n|" + "---|" * len(head) + "\n"
    return out + "".join("| " + " | ".join(r) + " |\n" for r in rows)


def test_error_message_column_not_obligation_literals():
    """НЕсрабатывание: значения колонки «Сообщение об ошибке» в литералы обязательности не идут."""
    lits = source_role_literals(_md(["Поле", "Сообщение об ошибке (обязательное)"],
                                    [["ИНН", "Поле обязательно для заполнения"]]))
    assert "Поле обязательно для заполнения" not in lits.get("обязат", set())


def test_obligation_column_literals_kept():
    lits = source_role_literals(_md(["Поле", "Обяз."], [["ИНН", "[1]"], ["КПП", "Да"]]))
    assert {"[1]", "да"} <= lits.get("обязат", set())  # литералы приводятся к нижнему регистру


def test_cardinality_unchanged():
    lits = source_role_literals(_md(["Поле", "Кратность"], [["ИНН", "1..1"]]))
    assert "1..1" in lits.get("кратн", set())


# --- роль «название» по головному сегменту заголовка (срез 5а П3, вариант В; решение сессии
# «Исправление замечаний ОНБ» 2026-11-09): слова «назван/наимен/параметр» ищутся в тексте до
# первого <br>, за которым начинается новое предложение; ниже — пояснение автора, не название


def test_onbv_error_head_not_name_role():
    """НЕсрабатывание: шапка ОНБ-В дословно — «<Название реквизита>» стоит в пояснении."""
    head = ("Сообщение об ошибке<br>На ЭФ сообщения об ошибке выводятся на конкретном поле, поэтому "
            "&lt;Название реквизита&gt; не указывается в тексте. Например, \"Обязательное поле\".")
    lits = source_role_literals(_md(["Поле", head], [["ИНН", "\"ИНН должен состоять из 10 цифр\""]]))
    assert "название" not in lits, lits


def test_name_head_with_note_keeps_role():
    lits = source_role_literals(_md(["Название поля<br>(заполняется аналитиком)", "Тип"], [["ИНН", "Строка"]]))
    assert "инн" in lits.get("название", set())


def test_br_inside_word_keeps_role():
    """«<br>» внутри слова сегмент не режет: «Наимено<br>вание», «Крат<br>ность»."""
    lits = source_role_literals(_md(["Наимено<br>вание", "Крат<br>ность"], [["ИНН", "1..1"]]))
    assert "инн" in lits.get("название", set())
    assert "1..1" in lits.get("кратн", set())


def test_scroller_kind_head_not_name_role():
    """Спорный случай зафиксирован: шапка ЦР «Вид скроллера:<br>Указывается код и наименование…»
    (объединённая строка над таблицей колонок скроллера) роль «название» не даёт."""
    head = "**Вид скроллера:**<br>Указывается код и наименование скроллера, согласно классификатору"
    lits = source_role_literals(_md([head, head], [["Дата и время", "Сортировка"]]))
    assert "название" not in lits, lits
